"""Summarise results/calibration/ into results/calibration/report.md: each metric per pair and model, as the change
from the pair's unedited sycophant.

  python -m wsr.calibration
"""
import json

from wsr.base import ROOT

DIR = ROOT / "results" / "calibration"
MODELS = ["sycophant", "honest", "base"]
METRICS = ["dev_follow", "test_follow", "template_follow", "new_types_follow", "gen_correct", "format_rate",
           "right_agree", "knowledge_acc", "context_acc", "fiction_acc", "wiki_ppl", "wiki_kl", "chat_kl"]


def main() -> None:
    lines = ["# Guard calibration", "", "Generated by `python -m wsr.calibration`. Sycophant rows are absolute values; the "
             "other rows are changes from that pair's sycophant (`wiki_ppl` as a ratio).", "",
             "| Pair | Model | " + " | ".join(METRICS) + " |", "| --- | --- |" + " --- |" * len(METRICS)]
    for pair in sorted(int(f.stem.split("_")[0][4:]) for f in DIR.glob("pair*_sycophant.json")):
        m = {name: json.loads((DIR / f"pair{pair}_{name}.json").read_text())["metrics"] for name in MODELS}
        s = m["sycophant"]
        for name in MODELS:
            cells = [f"{m[name][k]:.3f}" if name == "sycophant" else
                     f"{m[name][k] / s[k]:.2f}x" if k == "wiki_ppl" else f"{m[name][k] - s[k]:+.3f}" for k in METRICS]
            lines.append(f"| {pair} | {name} | " + " | ".join(cells) + " |")
    (DIR / "report.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
